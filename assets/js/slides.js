/*
 * Compositions, not templates.
 *
 * The first version of this file drew a centred block of one type size
 * on a flat rectangle, six times, and it looked like every generated
 * poster on the internet. What the references are actually doing is
 * harder and it is all in the arrangement: every line at its own size,
 * type cropped by the frame, an object with no box around it, weight
 * pushed off centre, and a small amount of editorial furniture holding
 * it together.
 *
 * Each of these is modelled on a specific reference, named against it.
 */
const LAYOUT = {

  /* 5409, 5422 — every line filling the measure, so a short line is
     enormous and a long one small. Left-aligned hard, bled off the top,
     weight low in the frame. */
  stack(ctx, s, g) {
    ctx.fillStyle = g.bg;
    ctx.fillRect(0, 0, WIDTH, HEIGHT);
    if (s.texture === 'grid') gridPaper(ctx, g);

    const measure = WIDTH - MARGIN * 2 + 40;       // slightly past the margin
    const lines = fillLines(ctx, s.copy, measure, { max: 260 });
    const block = lines.reduce((a, l) => a + l.size * 0.86, 0);
    drawFilled(ctx, lines, MARGIN - 6, HEIGHT * 0.62 - block, g.ink, g.mark);

    if (s.kicker) vertical(ctx, s.kicker, { x: MARGIN - 34, y: HEIGHT - MARGIN * 2, colour: g.ink });
  },

  /* 5426, 5415 — an object on colour with no box, bleeding off the
     bottom, type arched over it and a sticker at an angle. */
  cutout(ctx, s, g) {
    ctx.fillStyle = g.bg;
    ctx.fillRect(0, 0, WIDTH, HEIGHT);
    if (s.texture === 'grid') gridPaper(ctx, g);

    const lines = fillLines(ctx, s.copy, WIDTH - MARGIN * 2, { max: 200 });
    drawFilled(ctx, lines, MARGIN, MARGIN + 26, g.ink, g.mark);

    if (s.image) {
      place(ctx, s.image, { height: HEIGHT * 0.52, anchorX: 0.54, bottom: -HEIGHT * 0.03 });
    }
    if (s.badge) {
      badge(ctx, s.badge, { x: WIDTH - MARGIN - 60, y: HEIGHT * 0.56, angle: -11,
                            bg: g.mark, ink: g.bg });
    }
  },

  /* 5404 — a magazine page. Header rule, title, a plate that bleeds off
     the right, a row of small labels, a barcode in the corner. */
  editorial(ctx, s, g) {
    ctx.fillStyle = g.bg;
    ctx.fillRect(0, 0, WIDTH, HEIGHT);
    header(ctx, g, { left: s.handle || '@web3ashley', right: s.kicker || '' });

    const lines = fillLines(ctx, s.copy, WIDTH - MARGIN * 2, { max: 170 });
    let y = drawFilled(ctx, lines, MARGIN, MARGIN + 40, g.ink, g.mark);

    if (s.image) {
      // bleeds off the right edge — a picture that stops short of the
      // margin on both sides is a picture in a box
      const box = { x: MARGIN, y: y + 46, w: WIDTH - MARGIN + 40, h: HEIGHT - y - 300 };
      plate(ctx, s.image, { ...PHOTO, contrast: 1.45, box });
      y = box.y + box.h;
    }

    ctx.font = `24px ${MONO}`;
    ctx.fillStyle = g.ink;
    ctx.globalAlpha = 0.8;
    let lx = MARGIN;
    for (const label of (s.items || []).slice(0, 3)) {
      ctx.fillText(String(label).toUpperCase(), lx, y + 62);
      lx += ctx.measureText(String(label).toUpperCase()).width + 54;
    }
    ctx.globalAlpha = 1;
    barcode(ctx, { x: WIDTH - MARGIN - 210, y: HEIGHT - MARGIN - 84, w: 210, h: 56, colour: g.ink });
  },

  /* 5417, 5401 — one enormous figure cropped by the frame, with small
     text pairs pushed out to the margins around it. */
  figure(ctx, s, g) {
    ctx.fillStyle = g.bg;
    ctx.fillRect(0, 0, WIDTH, HEIGHT);

    const figure = String(s.figure ?? '');
    let size = 620;
    ctx.font = `800 ${size}px ${DISPLAY}`;
    // sized past the measure on purpose: the numeral is meant to be cut
    size = Math.min(size, size * ((WIDTH + 90) / ctx.measureText(figure).width));
    ctx.font = `800 ${size}px ${DISPLAY}`;
    ctx.fillStyle = g.ink;
    ctx.fillText(figure, MARGIN - size * 0.06, HEIGHT * 0.54);

    ctx.font = `26px ${MONO}`;
    ctx.globalAlpha = 0.8;
    if (s.kicker) ctx.fillText(String(s.kicker).toUpperCase(), MARGIN, MARGIN + 30);
    if (s.caption) {
      const cap = fillLines(ctx, s.caption, WIDTH * 0.62, { max: 64, min: 30 });
      ctx.globalAlpha = 1;
      drawFilled(ctx, cap, MARGIN, HEIGHT * 0.58, g.ink, g.mark, { leading: 1.16 });
    }
    ctx.globalAlpha = 1;
  },

  /* 5406, 5405 — words at different sizes and positions with an object
     running between them, so the type and the picture interleave rather
     than stack. */
  scatter(ctx, s, g) {
    ctx.fillStyle = g.bg;
    ctx.fillRect(0, 0, WIDTH, HEIGHT);

    const lines = fillLines(ctx, s.copy, WIDTH - MARGIN * 2, { max: 210 });
    const first = lines.slice(0, 1);
    const rest = lines.slice(1);
    const block = rest.reduce((a, l) => a + l.size * 0.86, 0);

    /*
     * The object goes down before any of the type, and into the band
     * between the two blocks rather than across them.
     *
     * Drawn after the first line and before the rest, it landed on top
     * of the words and took out a whole sentence. In the reference the
     * cord passes behind the type, not over it: the picture is what the
     * words are standing on.
     */
    if (s.image) {
      const top = MARGIN + (first[0] ? first[0].size : 0) * 0.9;
      const room = (HEIGHT - MARGIN * 1.5 - block) - top;
      place(ctx, s.image, {
        height: Math.max(HEIGHT * 0.2, Math.min(HEIGHT * 0.44, room * 1.25)),
        anchorX: 0.78,
        bottom: HEIGHT - (top + room) - 10,
        rotate: s.rotate ?? -6,
      });
    }

    drawFilled(ctx, first, MARGIN, MARGIN + 30, g.ink, g.mark);
    drawFilled(ctx, rest, MARGIN, HEIGHT - MARGIN * 1.5 - block, g.ink, g.mark);
  },

  /* Kept from the first pass because a plain statement still has a job:
     it is the slide that carries a single sentence and nothing else.
     Left and low rather than centred, and cropped at the measure. */
  statement(ctx, s, g) {
    ctx.fillStyle = g.bg;
    ctx.fillRect(0, 0, WIDTH, HEIGHT);
    if (s.texture === 'grid') gridPaper(ctx, g);
    const lines = fillLines(ctx, s.copy, WIDTH - MARGIN * 2, { max: 230 });
    const block = lines.reduce((a, l) => a + l.size * 0.86, 0);
    drawFilled(ctx, lines, MARGIN, HEIGHT * 0.66 - block, g.ink, g.mark);
  },
};

