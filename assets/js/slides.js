/**
 * A photograph as a cut-out: ink where the subject is, nothing where it
 * is not.
 *
 * The references never put a picture in a rectangle. An object sits on
 * the colour with type running behind and in front of it, and that is
 * most of why they look made rather than filled in. A rectangle is the
 * single most template-looking thing you can put on a slide.
 *
 * Real cut-out PNGs are better and are what this takes once they exist.
 * Until then a threshold gets there from an ordinary photograph: keep
 * the dark, drop the light, dither the edge so it does not look like a
 * selection. High-contrast subjects work; a grey sky does not, which is
 * a limitation of the source rather than the method.
 */
export function silhouette(img, { ink = '#080807', tone = '#e8e8e3', tolerance = 62 } = {}) {
  const c = document.createElement('canvas');
  c.width = img.width; c.height = img.height;
  const g = c.getContext('2d');
  g.drawImage(img, 0, 0);

  const d = g.getImageData(0, 0, c.width, c.height);
  const px = d.data;

  /*
   * The background is whatever the corners agree on.
   *
   * A luminance threshold was the first attempt and it is wrong: on a
   * dark photograph every pixel falls below the cut, nothing goes
   * transparent, and what comes out is a black rectangle — which is
   * exactly the thing a cut-out exists to avoid. Corners are a better
   * guess because a photograph of an object on a sweep has the sweep in
   * all four of them, and a photograph that does not will fail visibly
   * rather than quietly.
   */
  const corner = (x, y) => {
    const i = (y * c.width + x) * 4;
    return [px[i], px[i + 1], px[i + 2]];
  };
  const marks = [corner(2, 2), corner(c.width - 3, 2),
                 corner(2, c.height - 3), corner(c.width - 3, c.height - 3)];
  const bg = [0, 1, 2].map((k) => marks.reduce((a, m) => a + m[k], 0) / marks.length);

  const [ir, ig, ib] = hex(ink);
  const [tr, tg, tb] = hex(tone);

  for (let y = 0; y < c.height; y++) {
    for (let x = 0; x < c.width; x++) {
      const i = (y * c.width + x) * 4;
      const dr = px[i] - bg[0], dg = px[i + 1] - bg[1], db = px[i + 2] - bg[2];
      const far = Math.sqrt(dr * dr + dg * dg + db * db);

      if (far < tolerance) { px[i + 3] = 0; continue; }

      // what survives is dithered to two inks, so the object reads as
      // printed rather than as a photograph with its corners knocked out
      const l = (0.2126 * px[i] + 0.7152 * px[i + 1] + 0.0722 * px[i + 2]) / 255;
      const light = l > BAYER[y & 7][x & 7] * 0.9 + 0.16;
      px[i] = light ? tr : ir;
      px[i + 1] = light ? tg : ig;
      px[i + 2] = light ? tb : ib;
      // feather the last few units of tolerance so the edge is not a
      // hard line traced round the subject
      px[i + 3] = far > tolerance * 1.5 ? 255 : Math.round(((far - tolerance) / (tolerance * 0.5)) * 255);
    }
  }
  g.putImageData(d, 0, 0);
  return trim(c);
}

/** Crop to what is actually opaque, so `place` positions the object. */
function trim(c) {
  const g = c.getContext('2d');
  const { data, width, height } = g.getImageData(0, 0, c.width, c.height);
  let top = height, left = width, right = 0, bottom = 0;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (data[(y * width + x) * 4 + 3] > 12) {
        if (y < top) top = y;
        if (y > bottom) bottom = y;
        if (x < left) left = x;
        if (x > right) right = x;
      }
    }
  }
  if (right <= left || bottom <= top) return c;      // nothing survived
  const out = document.createElement('canvas');
  out.width = right - left + 1;
  out.height = bottom - top + 1;
  out.getContext('2d').drawImage(c, left, top, out.width, out.height, 0, 0, out.width, out.height);
  return out;
}

/**
 * Place a cut-out so it bleeds off an edge.
 *
 * Nothing in the folder is centred with a margin all round. The object
 * is always leaving the frame somewhere, which is what stops it looking
 * placed and starts it looking cropped from something bigger.
 */
export function place(ctx, img, { height, anchorX = 0.5, bottom = 0, rotate = 0 }) {
  const scale = height / img.height;
  const w = img.width * scale;
  const x = (WIDTH - w) * anchorX;
  const y = HEIGHT - height - bottom;
  ctx.save();
  if (rotate) {
    ctx.translate(x + w / 2, y + height / 2);
    ctx.rotate(rotate * Math.PI / 180);
    ctx.drawImage(img, -w / 2, -height / 2, w, height);
  } else {
    ctx.drawImage(img, x, y, w, height);
  }
  ctx.restore();
}

/* -------------------------------------------------------------- grounds */

/** Graph paper, from 5411. A ground with a grid on it is still quiet. */
function gridPaper(ctx, g, step = 46) {
  ctx.save();
  ctx.strokeStyle = g.ink;
  ctx.globalAlpha = 0.14;
  ctx.lineWidth = 1;
  ctx.beginPath();
  for (let x = 0; x <= WIDTH; x += step) { ctx.moveTo(x + 0.5, 0); ctx.lineTo(x + 0.5, HEIGHT); }
  for (let y = 0; y <= HEIGHT; y += step) { ctx.moveTo(0, y + 0.5); ctx.lineTo(WIDTH, y + 0.5); }
  ctx.stroke();
  ctx.restore();
}

/* ---------------------------------------------------------- furniture */

/** A sticker, set at an angle, from 5426. */
function badge(ctx, text, { x, y, angle = -8, bg, ink }) {
  ctx.save();
  ctx.translate(x, y);
  ctx.rotate(angle * Math.PI / 180);
  ctx.font = `700 26px ${MONO}`;
  const w = ctx.measureText(text).width + 44;
  const h = 60;
  ctx.fillStyle = bg;
  // a rounded slab, not a rectangle with a border
  const r = 30;
  ctx.beginPath();
  ctx.moveTo(-w / 2 + r, -h / 2);
  ctx.arcTo(w / 2, -h / 2, w / 2, h / 2, r);
  ctx.arcTo(w / 2, h / 2, -w / 2, h / 2, r);
  ctx.arcTo(-w / 2, h / 2, -w / 2, -h / 2, r);
  ctx.arcTo(-w / 2, -h / 2, w / 2, -h / 2, r);
  ctx.fill();
  ctx.fillStyle = ink;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText(text.toUpperCase(), 0, 2);
  ctx.restore();
  ctx.textAlign = 'left';
  ctx.textBaseline = 'alphabetic';
}

/** Type running up the left edge, from 5411's MONDAY. */
function vertical(ctx, text, { x, y, colour, size = 24 }) {
  ctx.save();
  ctx.translate(x, y);
  ctx.rotate(-Math.PI / 2);
  ctx.font = `${size}px ${MONO}`;
  ctx.fillStyle = colour;
  ctx.globalAlpha = 0.8;
  ctx.fillText(text.toUpperCase(), 0, 0);
  ctx.restore();
}

/** A barcode, from 5399 and 5404. Furniture, and nobody scans it. */
function barcode(ctx, { x, y, w, h, colour }) {
  ctx.save();
  ctx.fillStyle = colour;
  let cursor = x;
  let seed = 7;
  while (cursor < x + w) {
    seed = (seed * 1103515245 + 12345) & 0x7fffffff;
    const bar = 2 + (seed >> 16) % 6;
    if ((seed >> 8) % 3) ctx.fillRect(cursor, y, bar, h);
    cursor += bar + 2 + (seed >> 12) % 4;
  }
  ctx.restore();
}

/** The header bar, from 5404: handle, subject and index, in one rule. */
function header(ctx, g, { left, middle, right }) {
  ctx.font = `24px ${MONO}`;
  ctx.fillStyle = g.ink;
  ctx.globalAlpha = 0.7;
  ctx.textBaseline = 'alphabetic';
  if (left) ctx.fillText(String(left).toUpperCase(), MARGIN, MARGIN);
  if (middle) {
    ctx.textAlign = 'center';
    ctx.fillText(String(middle).toUpperCase(), WIDTH / 2, MARGIN);
    ctx.textAlign = 'left';
  }
  if (right) {
    ctx.textAlign = 'right';
    ctx.fillText(String(right).toUpperCase(), WIDTH - MARGIN, MARGIN);
    ctx.textAlign = 'left';
  }
  ctx.globalAlpha = 1;
}



/**
 * The handle, the index, and the swipe cue.
 *
 * Small marks in mono that make a slide look issued rather than posted.
 * Every reference in the folder has some version of this and none of
 * them makes anything of it, which is the point.
 */
function furniture(ctx, { ink, mark }, { index, total, handle = '@web3ashley', first }) {
  // 26px on a 1024 frame is about 2.5% of the width, which survives
  // being looked at on a phone. 22 did not.
  ctx.font = `26px ${MONO}`;
  ctx.textBaseline = 'alphabetic';
  ctx.globalAlpha = 0.72;

  ctx.fillStyle = ink;
  ctx.textAlign = 'left';
  ctx.fillText(handle, MARGIN, HEIGHT - 52);

  if (total > 1) {
    ctx.textAlign = 'right';
    ctx.fillText(`${String(index + 1).padStart(2, '0')}/${String(total).padStart(2, '0')}`,
                 WIDTH - MARGIN, HEIGHT - 52);
  }
  ctx.globalAlpha = 1;

  // only the first slide asks to be swiped; after that it is nagging
  if (first && total > 1) {
    ctx.fillStyle = mark;
    ctx.textAlign = 'right';
    ctx.font = `26px ${MONO}`;
    ctx.fillText('SWIPE →', WIDTH - MARGIN, MARGIN + 8);
  }
  ctx.textAlign = 'left';
}

