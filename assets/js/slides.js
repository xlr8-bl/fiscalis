/**
 * slides.js — carousel slides, drawn rather than generated.
 *
 * Six layouts, read off the reference folder. Nothing here calls a
 * model: every slide is type, flat colour, and a photograph from the
 * library put through a dither. That is deliberate. The argument this
 * account is making is that the work is made by a person, and generated
 * imagery is now the fastest way to say the opposite.
 *
 * What the references had in common, which is what this implements:
 *
 *   type is the subject      the headline takes a third to two thirds
 *                            of the frame; the picture supports it
 *   flat saturated grounds   never a gradient
 *   a grotesque and an       Bricolage against Instrument Serif
 *   italic, paired           Italic — the single most repeated device
 *                            in the folder
 *   print texture            dither and grain, so nothing is clean
 *   furniture                a handle, an index, a swipe cue
 *   two or three colours     never more
 *
 * Everything renders to a 1024x1280 canvas: 4:5, which is the ratio the
 * references are drawn at and the one both platforms accept without a
 * crop. What you see in the preview is the file that posts.
 */

export const WIDTH = 1024;
export const HEIGHT = 1280;

/*
 * The grounds, each carrying the ink that actually reads on it. Measured
 * rather than chosen by eye — cream on red is 3.53 and black on red is
 * 4.61, so red takes black type, and the rule holds for the rest:
 *
 *   red          black  4.61      ultramarine  cream  6.58
 *   yellow       black 12.29      black        cream 16.30
 *   newsprint    black 16.30
 *
 * `mark` is the third colour, spent only on furniture and one accent
 * word. Three is the ceiling the references never break.
 */
export const GROUNDS = {
  red: { bg: '#ED2024', ink: '#080807', mark: '#e8e8e3' },
  ultramarine: { bg: '#1B33E0', ink: '#e8e8e3', mark: '#F5C518' },
  yellow: { bg: '#F5C518', ink: '#080807', mark: '#1B33E0' },
  black: { bg: '#080807', ink: '#e8e8e3', mark: '#ED2024' },
  newsprint: { bg: '#e8e8e3', ink: '#080807', mark: '#ED2024' },
};

/*
 * The accent is the italic word and the furniture, so it has to read.
 * Red was the obvious mark everywhere and it fails on two grounds —
 * 1.86 on ultramarine and 2.67 on yellow, both under the 3.0 a display
 * word needs. So the two loud grounds accent each other instead, at
 * 4.96 both ways, which is also a pairing the reference folder uses.
 *
 *   red         cream        3.53
 *   ultramarine yellow       4.96
 *   yellow      ultramarine  4.96
 *   black       red          4.61
 *   newsprint   red          3.53
 *
 * A photograph is always black on cream, whatever it is sitting on. The
 * first attempt duotoned it into the ground, which works on a face and
 * fails on a landscape: a big flat sky becomes the ground exactly, and
 * the picture reads as a strip of texture rather than a picture. Black
 * on cream in a box always reads, and it is what the references do.
 */
export const PHOTO = { shadow: '#080807', highlight: '#e8e8e3' };

export const LAYOUTS = ['stack', 'cutout', 'editorial', 'figure', 'scatter', 'statement'];

const DISPLAY = '"Display", "Bricolage Grotesque", Arial, sans-serif';
const ITALIC = '"Accent", "Instrument Serif", Georgia, serif';
const MONO = '"Mono", ui-monospace, monospace';

const MARGIN = 84;

/* --------------------------------------------------------------- type */

/**
 * Load the three faces so a canvas can actually use them.
 *
 * A canvas falls back to a system face in silence if the family has not
 * loaded, and a slide set in the wrong typeface looks fine until it is
 * next to a right one. So they are loaded explicitly and awaited.
 */
let faces = null;
export function loadFaces() {
  if (faces) return faces;
  faces = Promise.all([
    ['Display', '/assets/fonts/bricolage.woff2', { weight: '800' }],
    ['Accent', '/assets/fonts/instrument-italic.woff2', { style: 'italic' }],
    ['Mono', '/assets/fonts/geistmono.woff2', {}],
  ].map(async ([name, url, desc]) => {
    try {
      const f = new FontFace(name, `url(${url}) format("woff2")`, desc);
      await f.load();
      document.fonts.add(f);
      return name;
    } catch { return null; }
  })).then((got) => got.filter(Boolean));
  return faces;
}

/**
 * Split copy into runs, where `{braces}` mark the italic.
 *
 *   "How to find your {Aesthetic}"
 *
 * The pairing is the device the whole reference folder is built on, and
 * it needs a way to say *which* word without a second field to fill in.
 * Braces are the least intrusive thing that survives being typed into a
 * form by a person and generated by an agent.
 */
export function runs(copy) {
  const out = [];
  for (const piece of String(copy || '').split(/(\{[^}]*\})/)) {
    if (!piece) continue;
    const italic = piece.startsWith('{') && piece.endsWith('}');
    out.push({ text: italic ? piece.slice(1, -1) : piece, italic });
  }
  return out;
}

const fontFor = (run, size) =>
  run.italic ? `italic ${size * 1.06}px ${ITALIC}` : `800 ${size}px ${DISPLAY}`;

/** Wrap mixed runs into lines, measuring each word in its own face. */
function wrap(ctx, parts, size, max) {
  const words = [];
  for (const part of parts) {
    for (const w of part.text.split(/(\s+)/)) {
      if (w.trim()) words.push({ text: w, italic: part.italic });
    }
  }
  const lines = [];
  let line = [];
  let width = 0;
  for (const w of words) {
    ctx.font = fontFor(w, size);
    const space = line.length ? ctx.measureText(' ').width : 0;
    const wide = ctx.measureText(w.text).width;
    if (line.length && width + space + wide > max) {
      lines.push(line); line = [w]; width = wide;
    } else {
      line.push(w); width += space + wide;
    }
  }
  if (line.length) lines.push(line);
  return lines;
}

/**
 * The largest size at which the copy still fits its box.
 *
 * Measured, not fixed. A fixed size has to be small enough for the
 * longest line anyone might write, which makes every short hook look
 * timid — and a timid hook is a slide nobody stops on.
 */
function fit(ctx, parts, box, { max = 168, min = 34 } = {}) {
  for (let size = max; size >= min; size -= 2) {
    const lines = wrap(ctx, parts, size, box.w);
    if (lines.length * size * 1.06 <= box.h) return { size, lines };
  }
  return { size: min, lines: wrap(ctx, parts, min, box.w) };
}

/**
 * Every line at its own size, each one filling the measure.
 *
 * This is the single device that separates a designed slide from a
 * caption on a rectangle, and the reference folder is full of it: BREAK
 * THE / PATTERN TODAY / OR THE / LOOP WILL, each line a different size
 * because each is set to span the same width. A short line comes out
 * enormous and a long one comes out small, and the ragged left-to-right
 * rhythm is what makes the block look composed rather than typed.
 *
 * Lines are given, not wrapped — where the line breaks is a design
 * decision, so it belongs in the copy as a newline.
 */
function fillLines(ctx, copy, measure, { max = 300, min = 30 } = {}) {
  return String(copy).split('\n').map((raw) => {
    const parts = runs(raw.trim());
    if (!parts.length) return null;
    let size = max;
    ctx.font = fontFor({ italic: false }, size);
    // one measure at a known size, then scale — binary-searching the
    // font size costs a measureText per step for no extra accuracy
    let width = 0;
    for (const part of parts) {
      ctx.font = fontFor(part, size);
      width += ctx.measureText(part.text).width;
    }
    if (width > 0) size = Math.max(min, Math.min(max, size * (measure / width)));
    return { parts, size };
  }).filter(Boolean);
}

/** Draw those lines, tight, each on its own baseline. */
function drawFilled(ctx, lines, x, y, colour, mark, { leading = 0.86 } = {}) {
  let cursor = y;
  for (const line of lines) {
    cursor += line.size * leading;
    let lx = x;
    for (const part of line.parts) {
      ctx.font = fontFor(part, line.size);
      ctx.fillStyle = part.italic && mark ? mark : colour;
      ctx.fillText(part.text, lx, cursor);
      lx += ctx.measureText(part.text).width;
    }
  }
  return cursor;
}

function drawLines(ctx, lines, size, x, y, colour, mark) {
  ctx.textBaseline = 'alphabetic';
  let cursor = y;
  for (const line of lines) {
    let lx = x;
    for (const w of line) {
      ctx.font = fontFor(w, size);
      // the italic is the accent word, so it takes the accent colour
      ctx.fillStyle = w.italic && mark ? mark : colour;
      ctx.fillText(w.text, lx, cursor);
      lx += ctx.measureText(w.text).width + ctx.measureText(' ').width;
    }
    cursor += size * 1.06;
  }
  return cursor;
}

/* ------------------------------------------------------------ texture */

/*
 * An 8x8 ordered dither. A threshold on its own gives hard shapes with
 * no tone at all; a Bayer matrix keeps the shape and puts the tone back
 * as a pattern, which is exactly what a newsprint screen does and what
 * the halftoned references are showing.
 */
const BAYER = (() => {
  const n = 8;
  const m = [];
  for (let y = 0; y < n; y++) {
    m[y] = [];
    for (let x = 0; x < n; x++) {
      let v = 0, mask = n >> 1, xc = x, yc = y;
      while (mask) {
        const bx = (xc & mask) ? 1 : 0, by = (yc & mask) ? 1 : 0;
        v = (v << 2) | ((bx ^ by) << 1 | bx);
        mask >>= 1;
      }
      m[y][x] = v / (n * n);
    }
  }
  return m;
})();

const hex = (h) => {
  const s = h.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16));
};

/**
 * A photograph as two inks, dithered.
 *
 * Cover-fitted rather than stretched: the library is full of landscape
 * pictures and this frame is portrait, so something has to be lost and
 * it should be the edges rather than the proportions of a face.
 */
export function plate(ctx, img, { shadow, highlight, contrast = 1.25, box = null }) {
  const b = box || { x: 0, y: 0, w: WIDTH, h: HEIGHT };
  const scale = Math.max(b.w / img.width, b.h / img.height);
  const w = img.width * scale, h = img.height * scale;

  ctx.save();
  ctx.beginPath();
  ctx.rect(b.x, b.y, b.w, b.h);
  ctx.clip();
  ctx.drawImage(img, b.x + (b.w - w) / 2, b.y + (b.h - h) / 2, w, h);
  ctx.restore();

  const data = ctx.getImageData(b.x, b.y, b.w, b.h);
  const px = data.data;
  const [sr, sg, sb] = hex(shadow);
  const [hr, hg, hb] = hex(highlight);

  for (let y = 0; y < b.h; y++) {
    for (let x = 0; x < b.w; x++) {
      const i = (y * b.w + x) * 4;
      let l = (0.2126 * px[i] + 0.7152 * px[i + 1] + 0.0722 * px[i + 2]) / 255;
      l = Math.min(1, Math.max(0, (l - 0.5) * contrast + 0.5));
      const light = l > BAYER[y & 7][x & 7];
      px[i] = light ? hr : sr;
      px[i + 1] = light ? hg : sg;
      px[i + 2] = light ? hb : sb;
      px[i + 3] = 255;
    }
  }
  ctx.putImageData(data, b.x, b.y);
}

/** Paper, so nothing on the slide is perfectly clean. */
let noise = null;
function grain(ctx, strength = 0.055) {
  if (!noise) {
    const c = document.createElement('canvas');
    c.width = c.height = 128;
    const g = c.getContext('2d');
    const d = g.createImageData(128, 128);
    for (let i = 0; i < d.data.length; i += 4) {
      const v = 120 + Math.random() * 135;
      d.data[i] = d.data[i + 1] = d.data[i + 2] = v;
      d.data[i + 3] = 255;
    }
    g.putImageData(d, 0, 0);
    noise = c;
  }
  ctx.save();
  ctx.globalAlpha = strength;
  ctx.globalCompositeOperation = 'overlay';
  const p = ctx.createPattern(noise, 'repeat');
  ctx.fillStyle = p;
  ctx.fillRect(0, 0, WIDTH, HEIGHT);
  ctx.restore();
}

