/**
 * Draw one slide onto a canvas.
 *
 * @param slide { layout, copy, figure, caption, kicker, items, image, ground }
 * @param meta  { index, total, handle }
 */
export async function drawSlide(canvas, slide, meta = {}) {
  await loadFaces();
  canvas.width = WIDTH;
  canvas.height = HEIGHT;
  const ctx = canvas.getContext('2d');
  const g = GROUNDS[slide.ground] || GROUNDS.red;
  const layout = LAYOUT[slide.layout] || LAYOUT.statement;

  ctx.clearRect(0, 0, WIDTH, HEIGHT);
  layout(ctx, slide, g);
  grain(ctx, g.bg === '#e8e8e3' ? 0.075 : 0.055);
  furniture(ctx, g, {
    index: meta.index ?? 0,
    total: meta.total ?? 1,
    handle: meta.handle,
    first: (meta.index ?? 0) === 0,
  });
  return canvas;
}

/**
 * Which ground a carousel runs on.
 *
 * One per carousel rather than one per slide: a set that changes colour
 * between slides reads as five posts, not one. The pillar decides it, so
 * the feed gains a rhythm nobody had to plan.
 */
export function groundFor(pillar, index = 0) {
  const order = ['red', 'black', 'ultramarine', 'newsprint', 'yellow'];
  const key = String(pillar || '');
  let n = 0;
  for (let i = 0; i < key.length; i++) n = (n * 31 + key.charCodeAt(i)) >>> 0;
  return order[(n + index) % order.length];
}
